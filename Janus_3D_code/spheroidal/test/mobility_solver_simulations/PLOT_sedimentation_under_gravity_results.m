this_dir = fileparts(mfilename('fullpath'));
repo_root = fileparts(fileparts(fileparts(this_dir)));
sim_data_dir = fullfile(repo_root, 'simulation_data', 'sedimentation-30body');
result_source = fullfile(sim_data_dir, 'matlab.mat');
snapshot_iteration = [];

opts = struct( ...
    'replay', true, ...
    'frameStep', 1, ...
    'pauseTime', 0.12, ...
    'finalPauseTime', 0, ...
    'summaryPlots', false, ...
    'saveAnimation', true, ...
    'animationFormat', 'gif', ...
    'animationPath', fullfile(repo_root, 'sedimentation_under_gravity'), ...
    'frameRate', 15, ...
    'plotTrajectories', false, ...
    'plotTrajMaxPoints', 400, ...
    'plotSurfaceAlpha', 0.6, ...
    'plotGrid', true, ...
    'plotColor', 'mu', ...
    'plotColorMode', 'l2', ...
    'plotColormap', 'turbo', ...
    'plotForceVectors', false, ...
    'plotView', [15 15], ...
    'plotTitle', 'Sedimentation under gravity', ...
    'plotShowTimestep', true ...
);

if ~isempty(snapshot_iteration)
    opts.replayStartStep = snapshot_iteration;
    opts.replayEndStep = snapshot_iteration;
    opts.frameStep = 1;
    opts.pauseTime = 0;
    opts.finalPauseTime = 0;
    opts.saveAnimation = false;
    opts.summaryPlots = false;

    plot_saved_mobility_results(result_source, opts);
    drawnow;
    snapshot_file = fullfile(repo_root, sprintf('sedimentation_snapshot_step_%d.png', snapshot_iteration));
    exportgraphics(gcf, snapshot_file, 'Resolution', 300);
    fprintf('Snapshot saved: %s\n', snapshot_file);
else
    plot_saved_mobility_results(result_source, opts);
end
