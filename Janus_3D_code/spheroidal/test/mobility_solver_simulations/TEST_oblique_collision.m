mdist = 1e-1;
collision_eps = 1e-1;

equ_radii = [0.6 0.6];
polar_radii = [1.0 1.0];
C = [...
    -0.58 0.0 -0.35; ...
     0.58 0.0  0.65; ...
];
shape_type = calculate_shape_type(equ_radii, polar_radii);

force_mag = 3.0;
F_const = [ force_mag, -force_mag; ...
            0.0,       0.0; ...
            0.0,       0.0 ];
Ffun = @(t, C, varargin) F_const;
