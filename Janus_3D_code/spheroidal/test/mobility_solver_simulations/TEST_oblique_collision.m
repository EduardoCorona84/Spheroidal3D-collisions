    'algo','moving_balls', ...
    'max_iter', 200, ...
    'tol',1e-7 ...
);
parbd = struct( ...
    'n3',n3, ...
    'equ_radii',equ_radii, ...
    'polar_radii',polar_radii, ...
    'shape_type',shape_type, ...
    'p',p, ...
    'Ct',C, ...
    'mdist',mdist, ...
    'collision_eps',collision_eps, ...
    'out',out, ...
    'bodydist', bodydist, ...
    'tsl_backend', bench_backend ...
