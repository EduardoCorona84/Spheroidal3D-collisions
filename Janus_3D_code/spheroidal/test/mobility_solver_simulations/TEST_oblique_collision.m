    'td_sparse_nn_inverse', 'lu', ...
    'td_sparse_nn_direct_max_bodies', 0, ...
    'td_sparse_nn_extract_max_bodies', 2, ...
    'td_sparse_nn_reuse_local_state', true, ...
    'td_sparse_nn_spai_reg', 1e-8, ...
    'td_sparse_nn_spai_drop_tol', 1e-10, ...
    'td_sparse_nn_compare_reference', true, ...
    'td_sparse_nn_compare_max_bodies', 2, ...
    'td_p_coarse', false, ...
    'td_low_rank', false, ...
    'td_two_level', false ...
);

