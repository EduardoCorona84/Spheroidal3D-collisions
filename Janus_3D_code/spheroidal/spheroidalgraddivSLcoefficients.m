function coeffs = spheroidalgraddivSLcoefficients(u, v, phi, n, m, is_oblate)
        %{
            Spectral coefficients for spheroidal graddiv SL. Not designed to be
            human readable.

            Ynm should be a cell of length 3, whose entries contain the coefficients
            associated with Ynm, and the entries correspond to the coefficient associated
            with f, f', and f'' IN ORDER (that is, the first entry corresponds to f's coefficients)
        %}
        coeffs = struct();
    
        if is_oblate
        error("not implemented.");
        else
        % --- U Component: GSHC_X ---
        coeffs.U.gshcx.Ynm = {
            (-1).*((-1)+u.^2).^(-1).*(u+(-1).*v).^(-3).*(u+v).^(-3).*(2.*u.^6+v.^2+v.^4+u.^2.*(2+(-4).*v.^2)+u.^4.*((-3)+v.^2));
            2.*u.*(u.^2+(-1).*v.^2).^(-1);
            ((-1)+u.^2).*(u.^2+(-1).*v.^2).^(-1)
        };
        coeffs.U.gshcx.Yn1m = { 0; 0; 0; };
        coeffs.U.gshcx.Yn2m = { 0; 0; 0; };
    
        % --- U Component: GSHC_Y ---
        coeffs.U.gshcy.Ynm = {
            u.*(u+(-1).*v).^(-3).*v.*(u+v).^(-3).*(((-1)+u.^2).^(-1).*(u+(-1).*v).*(u+v)).^(-1/2).*(((-1)+v.^2).^(-1).*((-1).*u.^2+v.^2)).^(1/2).*(3+(-1).*n.*u.^2+((-3)+n).*v.^2);
            (u+(-1).*v).^(-2).*v.*(u+v).^(-2).*(((-1)+u.^2).^(-1).*(u+(-1).*v).*(u+v)).^(-1/2).*(((-1)+v.^2).^(-1).*((-1).*u.^2+v.^2)).^(1/2).*((-1)+v.^2+n.*(u+(-1).*v).*(u+v));
            0;
        };
        coeffs.U.gshcy.Yn1m = {
            (1+(-1).*m+n).*((-1).*((-1)+m+(-1).*n).^(-1).*(1+m+n).*(1+2.*n).*(3+2.*n).^(-1)).^(1/2).*u.*(u+(-1).*v).^(-2).*(u+v).^(-2).*(((-1)+u.^2).^(-1).*(u+(-1).*v).*(u+v)).^(-1/2).*(((-1)+v.^2).^(-1).*((-1).*u.^2+v.^2)).^(1/2);
            ((-1)+m+(-1).*n).*((-1).*((-1)+m+(-1).*n).^(-1).*(1+m+n).*(1+2.*n).*(3+2.*n).^(-1)).^(1/2).*((-1)+u.^2).^(-1).*(((-1)+u.^2).^(-1).*(u+(-1).*v).*(u+v)).^(-3/2).*(((-1)+v.^2).^(-1).*((-1).*u.^2+v.^2)).^(1/2);
            0;
        };
        coeffs.U.gshcy.Yn2m = { 0; 0; 0; }
    
        % --- U Component: GSHC_Z ---
        coeffs.U.gshcz.Ynm = {
            sqrt(-1).*m.*u.*(((-1)+u.^2).^(-1).*(u+(-1).*v).*(u+v)).^(-1/2).*((-1)+v.^2).*((-1).*((-1)+u.^2).*((-1)+v.^2)).^(-3/2);
            sqrt(-1).*m.*(((-1)+u.^2).^(-1).*(u+(-1).*v).*(u+v)).^(-1/2).*((-1).*((-1)+u.^2).*((-1)+v.^2)).^(-1/2);
            0;
        };
        coeffs.U.gshcz.Yn1m = { 0; 0; 0; };
        coeffs.U.gshcz.Yn2m = { 0; 0; 0; };
        
        % --- V Component: GSHC_X ---
        coeffs.V.gshcx.Ynm = {
            u.*v.*(((-1)+u.^2).^(-1).*(u+(-1).*v).*(u+v)).^(1/2).*(u.^2+(-1).*v.^2).^(-4).*(((-1)+v.^2).^(-1).*((-1).*u.^2+v.^2)).^(1/2).*((-3)+2.*(1+n).*u.^4+(3+n).*v.^2+(2+n).*v.^4+(-1).*u.^2.*((-3)+n+(7+3.*n).*v.^2));
            ((-1)+u.^2).*v.*(((-1)+u.^2).^(-1).*(u+(-1).*v).*(u+v)).^(1/2).*(u.^2+(-1).*v.^2).^(-3).*(((-1)+v.^2).^(-1).*((-1).*u.^2+v.^2)).^(1/2).*(1+(1+n).*u.^2+(-1).*(2+n).*v.^2);
            0;
        };
        coeffs.V.gshcx.Yn1m = {
            ((-1)+m+(-1).*n).*((-1).*((-1)+m+(-1).*n).^(-1).*(1+m+n).*(1+2.*n).*(3+2.*n).^(-1)).^(1/2).*u.*(((-1)+u.^2).^(-1).*(u+(-1).*v).*(u+v)).^(1/2).*(u.^2+(-1).*v.^2).^(-3).*((-1)+2.*u.^2+(-1).*v.^2).*(((-1)+v.^2).^(-1).*((-1).*u.^2+v.^2)).^(1/2);
            ((-1)+m+(-1).*n).*((-1).*((-1)+m+(-1).*n).^(-1).*(1+m+n).*(1+2.*n).*(3+2.*n).^(-1)).^(1/2).*((-1)+u.^2).^(-1).*(((-1)+u.^2).^(-1).*(u+(-1).*v).*(u+v)).^(-3/2).*(((-1)+v.^2).^(-1).*((-1).*u.^2+v.^2)).^(1/2);
            0;
        };
        coeffs.V.gshcx.Yn2m = { 0; 0; 0; };
    
        % --- V Component: GSHC_Y ---
        coeffs.V.gshcy.Ynm = {
            (u+(-1).*v).^(-3).*(u+v).^(-3).*((-1)+v.^2).^(-1).*(u.^4+(-1).*(u+(-1).*v).^2.*(u+v).^2.*(1+n+2.*((-1)+m).*((1+(-1).*m+n).^(-1).*(1+m+n).*(1+2.*n).*(3+2.*n).^(-1)).^(1/2).*v+((-3)+m+(-1).*n).*n.*((1+(-1).*m+n).^(-1).*(1+m+n).*(1+2.*n).*(3+2.*n).^(-1)).^(1/2).*v+n.*(1+n).*v.^2)+u.^2.*(1+(-4).*v.^2+v.^4)+v.^2.*(2+(-3).*v.^2+2.*v.^4));
            0;
            0;
        };
        coeffs.V.gshcy.Yn1m = {
            (1+n).*(1+(-1).*m+n).*((1+(-1).*m+n).^(-1).*(1+m+n).*(1+2.*n).*(3+2.*n).^(-1)).^(1/2).*(u+(-1).*v).^(-1).*v.*(u+v).^(-1).*((-1)+v.^2).^(-1);
            0;
            0;
        };
        coeffs.V.gshcy.Yn2m = {
            ((-1)+m+(-1).*n).*(2+(-1).*m+n).*((1+(-1).*m+n).^(-1).*(1+m+n).*(1+2.*n).*(3+2.*n).^(-1)).^(1/2).*((2+(-1).*m+n).^(-1).*(2+m+n).*(3+2.*n).*(5+2.*n).^(-1)).^(1/2).*(u+(-1).*v).^(-1).*(u+v).^(-1).*((-1)+v.^2).^(-1);
            0;
            0;
        };
    
        % --- V Component: GSHC_Z ---
        coeffs.V.gshcz.Ynm = {
            sqrt(-1).*m.*(2+n).*((-1)+u.^2).*v.*((-1).*((-1)+u.^2).*((-1)+v.^2)).^(-3/2).*(((-1)+v.^2).^(-1).*((-1).*u.^2+v.^2)).^(-1/2);
            0;
            0;
        };
        coeffs.V.gshcz.Yn1m = {
            sqrt(-1).*m.*((-1)+m+(-1).*n).*((1+(-1).*m+n).^(-1).*(1+m+n).*(1+2.*n).*(3+2.*n).^(-1)).^(1/2).*((-1)+u.^2).*((-1).*((-1)+u.^2).*((-1)+v.^2)).^(-3/2).*(((-1)+v.^2).^(-1).*((-1).*u.^2+v.^2)).^(-1/2);
            0;
            0;
        };
        coeffs.V.gshcz.Yn2m = { 0; 0; 0; };

        % --- PHI Component: GSHC_X ---
        coeffs.PHI.gshcx.Ynm = {
            sqrt(-1).*m.*u.*(((-1)+u.^2).^(-1).*(u+(-1).*v).*(u+v)).^(1/2).*(u.^2+(-1).*v.^2).^(-2).*((-1)+2.*u.^2+(-1).*v.^2).*((-1).*((-1)+u.^2).*((-1)+v.^2)).^(-1/2);
            sqrt(-1).*m.*(((-1)+u.^2).^(-1).*(u+(-1).*v).*(u+v)).^(-1/2).*((-1).*((-1)+u.^2).*((-1)+v.^2)).^(-1/2);
            0;
        };
        coeffs.PHI.gshcx.Yn1m = { 0; 0; 0; };
        coeffs.PHI.gshcx.Yn2m = { 0; 0; 0; };
    
        % --- PHI Component: GSHC_Y ---
        coeffs.PHI.gshcy.Ynm = {
            sqrt(-1).*m.*v.*(u.^2+(-1).*v.^2).^(-2).*((-1).*((-1)+u.^2).*((-1)+v.^2)).^(-1/2).*(((-1)+v.^2).^(-1).*((-1).*u.^2+v.^2)).^(1/2).*((-1)+v.^2+n.*(u+(-1).*v).*(u+v));
            0;
            0;
        };
        coeffs.PHI.gshcy.Yn1m = {
            sqrt(-1).*m.*((-1)+m+(-1).*n).*((-1).*((-1)+m+(-1).*n).^(-1).*(1+m+n).*(1+2.*n).*(3+2.*n).^(-1)).^(1/2).*(u+(-1).*v).^(-1).*(u+v).^(-1).*((-1).*((-1)+u.^2).*((-1)+v.^2)).^(-1/2).*(((-1)+v.^2).^(-1).*((-1).*u.^2+v.^2)).^(1/2);
            0;
            0;
        };
        coeffs.PHI.gshcy.Yn2m = { 0; 0; 0; }
    
        % --- U Component: GSHC_Z ---
        coeffs.PHI.gshcz.Ynm = {
            m.^2.*((-1)+u.^2).^(-1).*((-1)+v.^2).^(-1);
            0;
            0;
        };
        coeffs.PHI.gshcz.Yn1m = { 0; 0; 0; };
        coeffs.PHI.gshcz.Yn2m = { 0; 0; 0; };
        end
    end